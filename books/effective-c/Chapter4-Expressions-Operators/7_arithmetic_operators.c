#include <stdio.h>

int main(void) {
    // Logical Negation Operator
    printf("!1: %d\n", !1);
    printf("!2: %d\n", !2);
    printf("!0: %d\n", !0);
    printf("!-2: %d\n", !-2);

    printf("--------------------------\n");

    printf("10 / 3: %d\n", 10 / 3);
    printf("-10 / 3: %d\n", -10 / 3);
    printf("10 / -3: %d\n", 10 / -3);
    printf("10 / 3: %f\n", 10 / 3);
    printf("10 / 3.0: %d\n", 10 / 3.0);
    printf("10 / 3.0: %f\n", 10 / 3.0);
}
